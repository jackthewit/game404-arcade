export function pickRandomRetroNickname(excludeName = '') {
  const pool = RETRO_ANIME_NICKNAMES.filter((n) => n !== excludeName);
  const list = pool.length > 0 ? pool : RETRO_ANIME_NICKNAMES;
  const arr = new Uint32Array(1);
  crypto.getRandomValues(arr);
  return list[arr[0] % list.length];
}
